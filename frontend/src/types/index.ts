// Define standard string literals for predefined Risk Levels
// Using a union type restricts this variable to ONLY be one of these three exact strings.
export type RiskLevel = 'HIGH' | 'MEDIUM' | 'LOW';

// Define standard string literals for the status of a specific medication dose
// PENDING: Not time yet, TAKEN: Patient took it, SKIPPED: Patient missed it
export type MedicationStatus = 'PENDING' | 'TAKEN' | 'SKIPPED';

// Define the structure (interface) for a Patient object
// This ensures every patient object strictly follows these rules, preventing bugs.
export interface Patient {
  // Unique identifier (e.g., 'P0001')
  patient_id: string;
  // Full name of the patient
  patient_name: string;
  // Patient's age in years
  age: number;
  // Patient's gender (Male/Female/Other)
  gender: string;
  // Total number of chronic conditions (e.g., Diabetes, Hypertension)
  chronic_conditions: number;
  // Number of active medications the patient is currently prescribed
  num_meds: number;
  // Historical adherence percentage (0-100), imported from ML dataset
  prior_adherence: number;
  // Historical count of how many doses they missed
  previous_missed_doses: number;
  // Historical count of how many pharmacy refills they missed
  previous_missed_refills: number;
  // The delay in days between when they should have refilled and when they actually did
  refill_gap_days: number;
  // The numerical 0-100 risk score generated by the mock ML logic (higher = higher risk)
  risk_score: number;
  // The categorized risk level (HIGH, MEDIUM, LOW) based on the risk_score
  risk_level: RiskLevel;
  // Optional (?) hashed password for authentication (used for new patients)
  password_hash?: string;
  // Optional (?) timestamp of when the patient registered
  created_at?: string;
  // Optional (?) raw object storing exact ML features parsed from the CSV dataset
  _raw_features?: any;
}

// Define the structure for a Medication prescription
export interface Medication {
  // Unique ID for this specific prescription (e.g., M001-1)
  medicine_id: string;
  // The ID of the patient this belongs to
  patient_id: string;
  // Name and dosage (e.g., 'Metformin 500mg')
  medicine_name: string;
  // How often they take it (e.g., 'Twice daily')
  frequency: string;
  // Array of specific times they are scheduled to take it (e.g., ['08:00 AM', '08:00 PM'])
  scheduled_times: string[];
  // When the prescription started
  start_date: string;
  // When the prescription ends
  end_date: string;
  // Total pills in the bottle
  quantity: number;
  // How many days until they need a refill
  refill_interval: number;
}

// Define the structure for a specific scheduled dose (a "Slot" in time)
// For example, if a medicine is taken twice daily, it generates two "Slots" per day.
export interface MedicationSlot {
  // Unique ID for this specific time slot
  slot_id: string;
  // The patient this belongs to
  patient_id: string;
  // The medicine this slot is for
  medicine_id: string;
  // The date this slot occurs (YYYY-MM-DD)
  date: string;
  // The time this slot occurs (e.g., '08:00 AM')
  scheduled_time: string;
  // Whether this specific slot is PENDING, TAKEN, or SKIPPED
  status: MedicationStatus;
}

// Define the structure for a historical event (when a patient actually takes action on a slot)
export interface MedicationEvent {
  // Unique ID for this action log
  event_id: string;
  // The patient who took the action
  patient_id: string;
  // The medicine involved
  medicine_id: string;
  // The specific time slot this action applies to
  slot_id: string;
  // The date of the slot
  date: string;
  // The expected time of the slot
  scheduled_time: string;
  // What the patient actually did (TAKEN or SKIPPED)
  status: MedicationStatus;
  // Optional (?) reason they provided if they skipped it
  skip_reason?: string;
  // Exact ISO timestamp of when they clicked the button
  timestamp: string;
}
